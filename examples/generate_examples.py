def write_csv(path: Path, header: list[str], rows: list[list]) -> None:
    with path.open("w", newline="", encoding="utf-8") as fh:
        w = csv.writer(fh, lineterminator="\n")
        w.writerow(header)
        w.writerows(rows)


def build(name: str, p: dict) -> None:
    rng = random.Random(p["seed"])
    cat_types = json.loads((CATALOGUE / "resource_types.json").read_text())
    modules = json.loads((CATALOGUE / "modules.json").read_text())["modules"]
    out = HERE / "portfolio" / name
    out.mkdir(parents=True, exist_ok=True)

    # The true universe has more accounts than anyone lists. Each independent source
    # (billing, org, sso) sees an account with its own probability; accounts no source
    # sees are hidden and do not appear in the files, which is what universe.py estimates.
    accounts = []
    seq = 0
    hidden = 0
    for provider, n in p["providers"].items():
        for i in range(n):
            seq += 1
            sources = [src for src in ("billing", "org", "sso") if rng.random() < p["detect"][src]]
            accounts.append({"id": f"{provider}-{i + 1:03d}", "provider": provider, "n": seq, "sources": sources})
    rng.shuffle(accounts)
    visible = []
    plan_count = 0
    for a in accounts:
        if not a["sources"]:
            if plan_count < p["plan"] and rng.random() < 0.25:     # known from the onboarding plan only
                a["sources"] = ["plan"]
            else:
                hidden += 1
                continue
        a["in_plan"] = plan_count < p["plan"]
        if a["in_plan"]:
            plan_count += 1
            if "plan" not in a["sources"]:
                a["sources"] = a["sources"] + ["plan"]
        a["owner"] = rng.choice(OWNERS)
        a["spend"] = round(rng.uniform(200, 9000), 0)
        a["created"] = AS_OF - timedelta(days=rng.randint(120, 900))
        a["connected"] = True
        visible.append(a)
    accounts = visible
    print(f"{name}: {len(accounts)} known accounts, {hidden} hidden from every source")
    plan_accounts = [a for a in accounts if a["in_plan"]]
    extra = [a for a in accounts if not a["in_plan"]]
    for a in rng.sample(plan_accounts, min(p["plan_unconnected"], len(plan_accounts))):
        a["connected"] = False
    unconnected_extra = rng.sample(extra, min(p["extra_unconnected"], len(extra)))
    for k, a in enumerate(unconnected_extra):
        a["connected"] = False
        if k < p["recent_unconnected"]:
            a["created"] = AS_OF - timedelta(days=rng.randint(3, 25))
            a["owner"] = "bu-retail" if name == "northwind" else a["owner"]
    accounts.sort(key=lambda a: a["id"])
    write_csv(
        out / "accounts.csv",
        ["id", "provider", "sources", "connected", "owner", "last_spend", "status", "in_plan", "created_at"],
        [[a["id"], a["provider"], ";".join(a["sources"]), str(a["connected"]).lower(), a["owner"], int(a["spend"]), "active",
          str(a["in_plan"]).lower(), a["created"].isoformat()] for a in accounts],
    )

    # Inventory and activations for connected accounts.
    inv, act = [], []
    present: dict[str, set[str]] = {}
    for a in accounts:
        if not a["connected"]:
            continue
        registry_gap = rng.random() < p["registry_missing"]
        present[a["id"]] = set()
        for t in cat_types["expected"].get(a["provider"], []):
            ok = not (t == "container_registry" and registry_gap) and rng.random() >= p["other_inventory_miss"]
            count = rng.randint(0, 5) if t == "ai_service" else rng.randint(1, 400)
            if t == "ai_service" and rng.random() < 0.4:
                count = 0
            inv.append([a["id"], t, count if ok else 0, str(ok).lower()])
            if ok and count > 0:
                present[a["id"]].add(t)
        for m in modules:
            if a["provider"] not in m["providers"]:
                continue
            act.append([a["id"], m["id"], str(rng.random() < p["module_p"][m["id"]]).lower()])
    write_csv(out / "inventory.csv", ["account_id", "resource_type", "count", "inventoried"], inv)
    write_csv(out / "activations.csv", ["account_id", "module_id", "active"], act)

    # Findings.
    connected_ids = [a["id"] for a in accounts if a["connected"]]
    rows = []
    fid = 0

    def finding(severity, exposure, age, closed_after=None, **kw):
        nonlocal fid
        fid += 1
        opened = AS_OF - timedelta(days=age)
        closed = opened + timedelta(days=closed_after) if closed_after is not None else None
        base = dict(owner="", decision="", reason="", expiry="", prev="", changed="")
        base.update(kw)
        rows.append([f"F-{fid:05d}", rng.choice(connected_ids), severity, exposure, opened.isoformat(),
                     closed.isoformat() if closed else "", base["owner"], base["decision"], base["reason"], base["expiry"], base["prev"], base["changed"]])

    n_open = p["findings"]
    crit_left = p["critical_open"]
    for _ in range(n_open):
        r = rng.random()
        severity = "critical" if crit_left > 0 and r < 0.08 else rng.choices(["high", "medium", "low"], [0.22, 0.48, 0.30])[0]
        if severity == "critical":
            crit_left -= 1
        exposure = "internet" if rng.random() < 0.25 else "internal"
        age = rng.randint(8, 45) if severity == "critical" else rng.randint(8, 190)
        x = rng.random()
        owner = rng.choice(OWNERS)
        if x < p["p_unowned"]:
            finding(severity, exposure, age)
        elif x < p["p_unowned"] + p["p_nodecision"]:
            finding(severity, exposure, age, owner=owner)
        elif x < p["p_unowned"] + p["p_nodecision"] + p["p_acc_noexp"]:
            finding(severity, exposure, age, owner=owner, decision="accepted_risk", reason="legacy dependency")
        elif x < p["p_unowned"] + p["p_nodecision"] + p["p_acc_noexp"] + p["p_acc_exp"]:
            finding(severity, exposure, age, owner=owner, decision="accepted_risk", reason="compensating control",
                    expiry=(AS_OF - timedelta(days=rng.randint(5, 60))).isoformat())
        else:
            dec = rng.choices(["fix", "accepted_risk", "exception", "false_positive"], [0.62, 0.14, 0.12, 0.12])[0]
            kw = dict(owner=owner, decision=dec)
            if dec == "accepted_risk":
                kw.update(reason="business exception", expiry=(AS_OF + timedelta(days=rng.randint(30, 180))).isoformat())
            finding(severity, exposure, age, **kw)
    # Recent findings (inside the triage window; not counted by L4).
    for _ in range(max(4, n_open // 20)):
        finding(rng.choice(["high", "medium", "low"]), "internal", rng.randint(0, 5))
    # Closed findings for MTTR and the streak.
    for _ in range(max(10, n_open // 3)):
        sev = rng.choices(["critical", "high", "medium", "low"], [0.1, 0.25, 0.4, 0.25])[0]
        if sev == "critical":
            took = max(1, int(rng.lognormvariate(1.8 if name != "fabrikam-labs" else 2.4, 0.8)))   # long tail, median ~6 days
        else:
            took = max(1, int(rng.gauss(SLA[sev] * (0.8 if name != "fabrikam-labs" else 1.3), SLA[sev] * 0.25)))
        closed_days_ago = rng.randint(1, 85)
        finding(sev, rng.choice(["internet", "internal"]), closed_days_ago + took, closed_after=took, owner=rng.choice(OWNERS), decision="fix")
    # Suspicious downgrades close to the SLA deadline.
    for _ in range(3 if name == "northwind" else 0):
        age = rng.randint(31, 45)
        changed = AS_OF - timedelta(days=age) + timedelta(days=SLA["high"] - 1)  # one day before the high-severity SLA deadline
        finding("medium", "internal", age, owner=rng.choice(OWNERS), decision="fix", prev="high", changed=changed.isoformat())
    write_csv(
        out / "findings.csv",
        ["id", "account_id", "severity", "exposure", "opened_at", "closed_at", "owner", "decision", "decision_reason", "expiry", "previous_severity", "severity_changed_at"],
        rows,
    )

    # Teams.
    n, with_users, with_sso, with_rbac, fresh = p["teams"]
    teams = []
    for i in range(n):
        tid = OWNERS[i] if i < len(OWNERS) else f"team-{i + 1:02d}"
        review = (AS_OF - timedelta(days=rng.randint(10, 80))).isoformat() if i < fresh else (AS_OF - timedelta(days=rng.randint(120, 400))).isoformat() if i % 3 else ""
        teams.append([tid, tid.replace("-", " ").title(), "true", rng.randint(2, 14) if i < with_users else 0,
                      str(i < with_sso).lower(), str(i < with_rbac).lower(), review])
    write_csv(out / "teams.csv", ["id", "name", "has_assets", "active_users", "sso", "role_scoped", "last_access_review"], teams)
    write_csv(out / "entitlements.csv", ["unit", "licensed", "used"], [[u, l, used] for u, (l, used) in p["entitlements"].items()])

    write_csv(out / "contacts.csv", ["id", "name", "role", "team", "influence", "last_contact", "credibility", "reliability", "intimacy", "self_orientation"],
              [[cid, nm, role, team, "", (AS_OF - timedelta(days=ago)).isoformat(), *ratings] for cid, nm, role, team, ago, ratings in CONTACTS[name]])
    write_csv(out / "commitments.csv", ["id", "contact_id", "description", "promised_on", "due_on", "done_on"], [list(c) for c in COMMITMENTS[name]])

    write_csv(out / "interactions.csv", ["date", "kind", "contact_id", "summary", "next_step", "next_due"],
              [[(AS_OF - timedelta(days=ago)).isoformat(), kind, who, text, step, (AS_OF + timedelta(days=due)).isoformat() if due is not None else ""]
               for ago, kind, who, text, step, due in INTERACTIONS[name]])

    (out / "customer.toml").write_text(
        f'''[customer]
name = "{name.replace("-", " ").title()} (mock)"
tier = "{p["tier"]}"
arr = {p["arr"]}
as_of = {AS_OF.isoformat()}
renewal_date = {RENEWALS[name]}

[settings]
ceiling_version = "2026.4"
baseline_ceiling = "2026.1"
triage_window_days = 7
entitlement_target = 0.8

[settings.sla_days]
critical = 7
high = 30
medium = 90
low = 180
''',
        encoding="utf-8",
    )


def read_csv(path: Path) -> tuple[list[str], list[dict]]:
    with path.open(newline="", encoding="utf-8") as fh:
        r = csv.DictReader(fh)
        return list(r.fieldnames or []), list(r)


def build_previous(name: str, days_back: int = 31) -> None:
    """The same customer a month earlier: fewer connected accounts, an older ceiling, fewer modules on.

    Derived from the current files so that `beyond90 explain` has a real before/after to attribute.
    """
    rng = random.Random(1000)
    src = HERE / "portfolio" / name
    out = HERE / "history" / f"{name}-{(AS_OF - timedelta(days=days_back)).strftime('%Y-%m')}"
    out.mkdir(parents=True, exist_ok=True)
    prev = AS_OF - timedelta(days=days_back)

    h, accounts = read_csv(src / "accounts.csv")
    accounts = [a for a in accounts if date.fromisoformat(a["created_at"]) <= prev]
    newly = {a["id"] for a in sorted((a for a in accounts if a["connected"] == "true" and a["in_plan"] == "true"), key=lambda a: a["id"])[:7]}
    for a in accounts:
        if a["id"] in newly:
            a["connected"] = "false"
    keep = {a["id"] for a in accounts}
    write_csv(out / "accounts.csv", h, [[a[k] for k in h] for a in accounts])

    h, inv = read_csv(src / "inventory.csv")
    inv = [r for r in inv if r["account_id"] in keep and r["account_id"] not in newly]
    for r in inv:
        if r["resource_type"] == "container_registry" and rng.random() < 0.2:
            r["inventoried"], r["count"] = "false", "0"
    write_csv(out / "inventory.csv", h, [[r[k] for k in h] for r in inv])

    h, act = read_csv(src / "activations.csv")
    act = [r for r in act if r["account_id"] in keep and r["account_id"] not in newly]
    for r in act:
        if r["active"] == "true" and r["module_id"] in ("runtime_sensor", "code_scanning") and rng.random() < 0.3:
            r["active"] = "false"
    write_csv(out / "activations.csv", h, [[r[k] for k in h] for r in act])

    h, fs = read_csv(src / "findings.csv")
    rows = []
    for f in fs:
        if date.fromisoformat(f["opened_at"]) > prev or f["account_id"] not in keep:
            continue
        if f["closed_at"] and date.fromisoformat(f["closed_at"]) > prev:
            f["closed_at"] = ""
        if f["severity_changed_at"] and date.fromisoformat(f["severity_changed_at"]) > prev:
            f["previous_severity"] = f["severity_changed_at"] = ""
        rows.append([f[k] for k in h])
    write_csv(out / "findings.csv", h, rows)

    h, ts = read_csv(src / "teams.csv")
    write_csv(out / "teams.csv", h, [[t[k] for k in h] for t in ts])
    h, es = read_csv(src / "entitlements.csv")
    for e in es:
        e["used"] = str(round(float(e["used"]) * 0.88))
    write_csv(out / "entitlements.csv", h, [[e[k] for k in h] for e in es])
    toml = (src / "customer.toml").read_text(encoding="utf-8")
    toml = toml.replace(f"as_of = {AS_OF.isoformat()}", f"as_of = {prev.isoformat()}").replace('ceiling_version = "2026.4"', 'ceiling_version = "2026.2"')
    (out / "customer.toml").write_text(toml, encoding="utf-8")


if __name__ == "__main__":
    for customer, profile in PROFILES.items():
        build(customer, profile)
    build_previous("northwind")
    print("Generated", ", ".join(PROFILES), "in", HERE / "portfolio", "and examples/history/")
